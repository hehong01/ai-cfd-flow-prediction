def extract_scaled_landmarks(image_path, target_height=200.0):
    """Extract one face and uniformly scale its landmark cloud by face height.

    Parameters
    ----------
    image_path : str or pathlib.Path
        Input JPG/JPEG/PNG image.
    target_height : float
        Target landmark height in millimeters. The original project used
        200.0 mm.

    Returns
    -------
    numpy.ndarray
        Array with shape (468, 3).
    """
    image_path = Path(image_path)

    image = cv2.imread(str(image_path))
    if image is None:
        raise ValueError(f"Image not found or unreadable: {image_path}")

    height, width, _ = image.shape

    with mp.solutions.face_mesh.FaceMesh(
        max_num_faces=1,
        refine_landmarks=True,
        min_detection_confidence=0.5,
        min_tracking_confidence=0.5,
    ) as face_mesh:
        results = face_mesh.process(cv2.cvtColor(image, cv2.COLOR_BGR2RGB))

    if not results.multi_face_landmarks:
        raise ValueError(f"No face landmarks detected: {image_path}")

    # Preserve the original behavior: use the first detected face and only
    # the first 468 landmarks referenced by MESH_INDEX.
    landmarks = results.multi_face_landmarks[0].landmark[:468]

    x = np.array([landmark.x * width for landmark in landmarks], dtype=float)
    y = np.array([landmark.y * height for landmark in landmarks], dtype=float)
    z = np.array([landmark.z * width for landmark in landmarks], dtype=float)

    x -= np.mean(x)
    y -= np.mean(y)
    z -= np.mean(z)

    current_height = np.max(y) - np.min(y)
    if current_height <= 0:
        raise ValueError("Detected landmarks have zero face height.")

    scale_factor = float(target_height) / current_height

    return np.stack(
        [x * scale_factor, y * scale_factor, z * scale_factor],
        axis=-1,
    )
